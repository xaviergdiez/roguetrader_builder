// The bestiary: antagonists with real numbers, ready to put on the board.
//
// This is the stat-carrying list. bestiaryindex.js is the other one — a
// lookup of book and page references with no numbers at all — and the two
// answer different questions: this one spawns a creature ready to fight,
// that one tells a GM which book to open.
//
// HOW THE NUMBERS ARE STORED, where the source needed a decision:
//
//   Per-location armour  A single `armour` figure is what the engine
//                        subtracts, so the BODY value is stored (most hits
//                        land there) and the full spread is kept in
//                        `armourNote` for the GM to apply by hand.
//   Unnatural scores     "59 (10)" is a Strength of 59 whose bonus is 10
//                        rather than the 5 its tens digit would give. The
//                        characteristic is stored plain; `toughnessBonus`
//                        is taken from the source's own TB column, which
//                        already accounts for Unnatural Toughness.
//   Spans               "37-45" covers several versions of one profile.
//                        The LOW end is stored — the common version — and
//                        the span is recorded in the note.
//   Swarm Wounds        "10/30/50" is a swarm thinning as it dies. The
//                        first figure is stored and the rest noted.
//   No numbers          a characteristic the source leaves blank is 0, and
//                        an entry the source gives nothing usable for is
//                        marked `custom: true` so the GM knows to run it by
//                        hand rather than trusting the zeros.
//
// WHERE THE SOURCES DISAGREE, the compiled master is followed and the
// conflict is recorded in `conflict` so nobody has to rediscover it. See
// CONFLICTS at the bottom for the list.

const B = (name, group, stats, weapon, abilities, extra = {}) => ({
  name, group,
  // A characteristic the source does not give is 0, not null. A beast that
  // cannot shoot has Ballistic Skill 0, which is what the printed profiles
  // mean by their dash: it may still be handed a gun, and it will miss.
  ws: 0, bs: 0, s: 0, t: 0, ag: 0,
  int: 0, per: 0, wp: 0, fel: 0,
  wounds: 0, toughnessBonus: 0, armour: 0,
  ...stats,
  weapon: weapon || null,
  abilities: abilities || null,
  armourNote: null, note: null, conflict: null, custom: false,
  ...extra
});

